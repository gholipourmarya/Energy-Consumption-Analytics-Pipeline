"""PostgreSQL storage for accepted readings, quarantined events and batch metrics."""

import os
from uuid import uuid4

import psycopg

SCHEMA = '''
CREATE TABLE IF NOT EXISTS public.warehouse_identity (
    singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
    warehouse_id UUID NOT NULL,
    legacy_checkpoint_id UUID
);

CREATE TABLE IF NOT EXISTS public.stream_events (
    topic TEXT NOT NULL,
    kafka_partition INTEGER NOT NULL,
    kafka_offset BIGINT NOT NULL,
    reading_id TEXT,
    meter_id TEXT,
    reading_date DATE,
    consumption_kwh DOUBLE PRECISION,
    high_consumption INTEGER,
    rejection_reason TEXT,
    payload TEXT,
    PRIMARY KEY (topic, kafka_partition, kafka_offset)
);

CREATE UNIQUE INDEX IF NOT EXISTS accepted_reading_id
ON public.stream_events (reading_id) WHERE rejection_reason IS NULL;

CREATE OR REPLACE VIEW public.readings AS
SELECT reading_id, meter_id, reading_date, consumption_kwh, high_consumption
FROM public.stream_events WHERE rejection_reason IS NULL;

CREATE OR REPLACE VIEW public.quarantine AS
SELECT topic, kafka_partition, kafka_offset, reading_id, rejection_reason, payload
FROM public.stream_events WHERE rejection_reason IS NOT NULL;

CREATE TABLE IF NOT EXISTS public.quality_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spark_batch_id BIGINT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    accepted INTEGER NOT NULL,
    rejected INTEGER NOT NULL,
    duplicates INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS quality_batches_recorded_at
ON public.quality_batches (recorded_at);
'''

INSERT_EVENT = '''
INSERT INTO public.stream_events VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
ON CONFLICT DO NOTHING RETURNING 1
'''


def connect():
    return psycopg.connect(
        host=os.environ.get('ENERGY_PG_HOST', '127.0.0.1'),
        port=os.environ.get('ENERGY_PG_PORT', '5432'),
        dbname=os.environ.get('ENERGY_PG_DATABASE', 'energy'),
        user=os.environ.get('ENERGY_PG_USER', 'energy'),
        password=os.environ.get('ENERGY_PG_PASSWORD', 'energy-local'),
        connect_timeout=10,
        options='-c timezone=UTC',
    )


def initialize():
    with connect() as con:
        con.execute('SELECT pg_advisory_xact_lock(49817724)')
        con.execute(SCHEMA)
        con.execute(
            'INSERT INTO public.warehouse_identity (warehouse_id) VALUES (%s) ON CONFLICT DO NOTHING',
            (uuid4(),),
        )
        return str(con.execute('SELECT warehouse_id FROM public.warehouse_identity').fetchone()[0])


def bind_checkpoint(state_dir, warehouse_id):
    checkpoint = state_dir / 'checkpoint'
    marker = state_dir / 'postgres-warehouse-id'
    if marker.exists():
        if marker.read_text(encoding='utf-8').strip() != warehouse_id:
            raise RuntimeError(f'PostgreSQL warehouse does not match the checkpoint in {state_dir}')
    elif (checkpoint / 'offsets').exists():
        raise RuntimeError(f'Existing checkpoint is not bound to PostgreSQL: {state_dir}')
    else:
        write_checkpoint_binding(state_dir, warehouse_id)
    return checkpoint


def write_checkpoint_binding(state_dir, warehouse_id):
    state_dir.mkdir(parents=True, exist_ok=True)
    pending = state_dir / 'postgres-warehouse-id.tmp'
    pending.write_text(f'{warehouse_id}\n', encoding='utf-8')
    pending.replace(state_dir / 'postgres-warehouse-id')


def persist_batch(rows, batch_id):
    accepted = rejected = duplicates = replayed = 0
    with connect() as con:
        for row in rows:
            identity = (row.topic, row.partition, row.offset, row.reading_id, row.meter_id, row.reading_date)
            reason = row.reason
            if reason is None:
                result = con.execute(
                    INSERT_EVENT, (*identity, row.consumption_kwh, row.high_consumption, None, None)
                )
                if result.fetchone():
                    accepted += 1
                    continue
                reason = 'duplicate_reading_id'

            result = con.execute(INSERT_EVENT, (*identity, None, None, reason, row.payload))
            if result.fetchone() is None:
                replayed += 1
            elif reason == 'duplicate_reading_id':
                duplicates += 1
            else:
                rejected += 1

        if accepted + rejected + duplicates:
            con.execute(
                'INSERT INTO public.quality_batches (spark_batch_id, accepted, rejected, duplicates) '
                'VALUES (%s, %s, %s, %s)',
                (batch_id, accepted, rejected, duplicates),
            )
    return accepted, rejected, duplicates, replayed
